package webhook

import (
	"chatbot-go/internal/intent"
	"testing"
)

// TestExplicitUpdateRequestsReachEditFlow [F33-41] user：「這些都得使用者主動跟bot說要更新」「後續功能要能協助改正計算正確」.
// 客人主動要求更新的說法，一定要進改紀錄流程（改紀錄關鍵字直接進規劃器，或過意圖閘門交給分類器）；
// 都沒中就只會走問答，不會出確認卡. 不呼叫 AI.
func TestExplicitUpdateRequestsReachEditFlow(t *testing.T) {
	for _, s := range []string{
		"餐包裡面其實有包起司鮮奶油餡，幫我更新熱量",
		"吐司有抹很厚的花生醬，幫我更新",
		"沙拉淋了很多凱薩醬，幫我改一下熱量",
		"我還有點一盤小菜，滷海帶跟豆干，幫我加上去",
		"牛肉麵有加酸菜，幫我算進去",
		"牛肉麵的湯我全部喝完了，幫我補上",
		"牛肉麵的湯我都沒喝，幫我扣掉",
		"餐包我其實吃了兩個，幫我調整",
		"便當我只吃了一半，熱量幫我減半",
		"雞胸肉其實是炸的，重新算一下",
		"紅茶其實是全糖還加了珍珠，幫我重算",
		"那個麵包裡面有大量起司鮮奶油，請重新分析",
		"小菜也要算進去",
		"幫我把滷蛋加進去",
		"湯有喝完要加上去",
		"你要直接更新正確啦", // [F33-46] 決策 2805c816 ④：從分類器正例移來
	} {
		if !EditGate(s) && !intent.PassesGate(s) {
			t.Errorf("客人主動要求更新卻進不了改紀錄流程（只會走問答）：%q", s)
		}
	}
}
